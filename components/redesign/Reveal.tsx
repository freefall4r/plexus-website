"use client";

import { motion } from "framer-motion";
import type { ReactNode } from "react";

/**
 * Reveal — slow, organic scroll-in (fade + 12px rise). Respects reduced motion
 * automatically via framer-motion. Use to wrap any block that should animate in.
 */
export function Reveal({
  children,
  delay = 0,
  y = 14,
  className,
}: {
  children: ReactNode;
  delay?: number;
  y?: number;
  className?: string;
}) {
  return (
    <motion.div
      className={className}
      initial={{ opacity: 0, y }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true, margin: "-10% 0px -10% 0px" }}
      transition={{ duration: 0.8, delay, ease: [0.16, 1, 0.3, 1] }}
    >
      {children}
    </motion.div>
  );
}
